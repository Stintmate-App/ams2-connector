"""Generate the v14 offset fixture and the Rust layout from the ctypes layout of an earlier Python
implementation of the connector (not in this repository; this script is the record of how they were made).

Usage (read-only against that implementation's source):
  uv run --no-project crates/ams2-shm/scripts/gen_layout.py <path to .../ams2_connector/shm> \
      <fixture.json> <layout_generated.rs>
"""
import ctypes
import importlib.util
import json
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]) / "layout.py"
spec = importlib.util.spec_from_file_location("ams2_layout", src)
mod = importlib.util.module_from_spec(spec)
sys.modules["ams2_layout"] = mod
spec.loader.exec_module(mod)


def snake(name: str) -> str:
    s = name[1:] if name.startswith("m") else name
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return s.lower()


SCALARS = {
    ctypes.c_bool: "u8",
    ctypes.c_char: "u8",
    ctypes.c_uint32: "u32",
    ctypes.c_int32: "i32",
    ctypes.c_float: "f32",
}


def rust_type(t) -> str:
    if t in SCALARS:
        return SCALARS[t]
    if hasattr(t, "_length_"):
        return f"[{rust_type(t._type_)}; {t._length_}]"
    if issubclass(t, ctypes.Structure):
        return t.__name__
    raise SystemExit(f"unsupported type {t}")


def emit(cls, out, fixture):
    name = cls.__name__
    out.append("#[derive(Debug, Clone, Copy, FromBytes, IntoBytes, KnownLayout, Immutable)]")
    out.append("#[repr(C)]")
    out.append(f"pub struct {name} {{")
    pos = 0
    pad = 0
    asserts = []
    table = []
    for fname, ftype in cls._fields_:
        d = getattr(cls, fname)
        off, size = d.offset, d.size
        if off > pos:
            out.append(f"    _pad{pad}: [u8; {off - pos}],")
            pad += 1
        rn = snake(fname)
        out.append(f"    /// `{fname}`")
        out.append(f"    pub {rn}: {rust_type(ftype)},")
        fixture[f"{name}.{fname}"] = {"offset": off, "size": size}
        asserts.append(
            f"const _: () = assert!(offset_of!({name}, {rn}) == {off} "
            f"&& size_of::<{rust_type(ftype)}>() == {size});"
        )
        table.append(f'    ("{name}.{fname}", offset_of!({name}, {rn}), size_of::<{rust_type(ftype)}>()),')
        pos = off + size
    total = ctypes.sizeof(cls)
    if total > pos:
        out.append(f"    _pad{pad}: [u8; {total - pos}],")
    out.append("}\n")
    out.append(f"const _: () = assert!(size_of::<{name}>() == {total});")
    out.extend(asserts)
    fixture[f"{name}"] = {"offset": 0, "size": total}
    out.append("")
    return table


fixture = {}
out = [
    "// @generated by crates/ams2-shm/scripts/gen_layout.py; do not edit by hand.",
    "use core::mem::{offset_of, size_of};",
    "use zerocopy::{FromBytes, Immutable, IntoBytes, KnownLayout};",
    "",
]
t1 = emit(mod.ParticipantInfo, out, fixture)
t2 = emit(mod.SharedMemory, out, fixture)
out.append("/// Every field as (`Struct.cName`, offset, size) as laid out by the Rust structs.")
out.append("pub const FIELD_TABLE: &[(&str, usize, usize)] = &[")
out.extend(t1 + t2)
out.append("];")
Path(sys.argv[3]).write_text("\n".join(out) + "\n", encoding="utf-8")
doc = {
    "shared_memory_version": mod.SHARED_MEMORY_VERSION,
    "mapping_name": mod.MAPPING_NAME,
    "size": ctypes.sizeof(mod.SharedMemory),
    "fields": fixture,
}
Path(sys.argv[2]).write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8")
